    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      String nome = jTextField1.getText().trim();
    String cpf = jTextField2.getText().trim();
    String endereco = jTextField3.getText().trim();
    
    if (nome.isEmpty() || cpf.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Preencha nome e CPF!");
        return;
    }   
    
    Cliente cliente = new Cliente("0", nome, cpf, endereco);
    ClienteDAO dao = new ClienteDAO();
    
    if (dao.inserir(cliente)) {
        JOptionPane.showMessageDialog(this, "Cliente cadastrado com sucesso!");
        limparCampos();
    } else {
        JOptionPane.showMessageDialog(this, "Erro ao cadastrar cliente!");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void limparCampos() {
    jTextField1.setText("");
    jTextField2.setText("");
    jTextField3.setText("");
}

