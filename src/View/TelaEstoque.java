    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int linhaSelecionada = jTable1.getSelectedRow();
    if (linhaSelecionada == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um produto para editar!");
        return;
    }
    
  
    String id = jTable1.getValueAt(linhaSelecionada, 0).toString();
    String nome = jTable1.getValueAt(linhaSelecionada, 1).toString();
    

    Object quantidadeObj = jTable1.getValueAt(linhaSelecionada, 2);
    String quantidadeStr = quantidadeObj.toString().trim();
   
    quantidadeStr = quantidadeStr.replaceAll("[^0-9]", "");
    
   
    Object precoObj = jTable1.getValueAt(linhaSelecionada, 3);
    String precoStr = precoObj.toString().trim();
  
    precoStr = precoStr.replace("R$", "").replace("$", "").trim();
   
    precoStr = precoStr.replace(",", ".");
  
    precoStr = precoStr.replaceAll("[^0-9.]", "");
    
    String tipo = jTable1.getValueAt(linhaSelecionada, 4).toString();
    
   
    System.out.println("Quantidade original: " + quantidadeObj);
    System.out.println("Quantidade limpa: " + quantidadeStr);
    System.out.println("Preço original: " + precoObj);
    System.out.println("Preço limpo: " + precoStr);
    
 
    JTextField txtNome = new JTextField(nome);
    JTextField txtPreco = new JTextField(precoStr);
    JTextField txtQuantidade = new JTextField(quantidadeStr);
    
    JComboBox<String> comboTipo = new JComboBox<>(new String[]{
        "Dobradiças", "Corrediças e Trilhos", "Puxadores e Maçanetas", 
        "Fechaduras e Trincos", "Suportes e Conectores", "Parafusos e Buchas", 
        "Pistões a Gás e Articuladores", "Perfis de Alumínio e Ferragens Decorativas", 
        "Ferramentas"
    });
    comboTipo.setSelectedItem(tipo);
    
    Object[] message = {
        "Nome:", txtNome,
        "Preço:", txtPreco,
        "Quantidade:", txtQuantidade,
        "Tipo:", comboTipo
    };
    
    int option = JOptionPane.showConfirmDialog(this, message, "Editar Produto", JOptionPane.OK_CANCEL_OPTION);
    if (option == JOptionPane.OK_OPTION) {
        try {
         
            if (txtNome.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "O nome do produto não pode estar vazio!");
                return;
            }
            
        
            String precoText = txtPreco.getText().trim().replace(",", ".");
            precoText = precoText.replaceAll("[^0-9.]", "");
            if (precoText.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Preço inválido!");
                return;
            }
            double preco = Double.parseDouble(precoText);
            
            String qtdText = txtQuantidade.getText().trim().replaceAll("[^0-9]", "");
            if (qtdText.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Quantidade inválida!");
                return;
            }
            int quantidade = Integer.parseInt(qtdText);
            
           
            if (preco <= 0) {
                JOptionPane.showMessageDialog(this, "O preço deve ser maior que zero!");
                return;
            }
            if (quantidade < 0) {
                JOptionPane.showMessageDialog(this, "A quantidade não pode ser negativa!");
                return;
            }
            
         
            Produto produto = new Produto(
                id, 
                txtNome.getText().trim(), 
                (String) comboTipo.getSelectedItem(), 
                false, 
                preco, 
                quantidade
            );
            
            ProdutoDAO dao = new ProdutoDAO();
            if (dao.atualizar(produto)) {
                JOptionPane.showMessageDialog(this, "Produto atualizado com sucesso!");
                carregarProdutos(); // Recarregar a tabela
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao atualizar produto!");
            }
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage() + "\nPreço e quantidade devem ser números válidos!");
            e.printStackTrace();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro inesperado: " + e.getMessage());
            e.printStackTrace();
        }
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int linhaSelecionada = jTable1.getSelectedRow();
    if (linhaSelecionada == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um produto para excluir!");
        return;
    }
    
    String id = jTable1.getValueAt(linhaSelecionada, 0).toString();
    String nome = jTable1.getValueAt(linhaSelecionada, 1).toString();
    
    int confirm = JOptionPane.showConfirmDialog(this, 
        "Deseja excluir o produto: " + nome + "?", 
        "Confirmar Exclusão", 
        JOptionPane.YES_NO_OPTION);
    
    if (confirm == JOptionPane.YES_OPTION) {
        ProdutoDAO dao = new ProdutoDAO();
        if (dao.excluir(Integer.parseInt(id))) {
            JOptionPane.showMessageDialog(this, "Produto excluído com sucesso!");
            carregarProdutos();
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao excluir produto!");
        }
    }
    }//GEN-LAST:event_jButton3ActionPerformed

