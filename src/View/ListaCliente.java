    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nome = jTextField1.getText().trim();
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    
    ClienteDAO dao = new ClienteDAO();
    List<Cliente> clientes;
    
    if (nome.isEmpty()) {
        clientes = dao.listarTodos();
    } else {
        clientes = dao.buscarPorNome(nome);
    }
    
    for (Cliente cliente : clientes) {
        model.addRow(new Object[]{
            cliente.getId(),
            cliente.getNome(),
            cliente.getCPF(),
            cliente.getEndereco()
        });
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
      int linhaSelecionada = jTable1.getSelectedRow();
    if (linhaSelecionada == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um cliente para excluir!");
        return;
    }
    
    String id = jTable1.getValueAt(linhaSelecionada, 0).toString();
    String nome = jTable1.getValueAt(linhaSelecionada, 1).toString();
    
    int confirm = JOptionPane.showConfirmDialog(this, 
        "Deseja excluir o cliente: " + nome + "?", 
        "Confirmar Exclusão", 
        JOptionPane.YES_NO_OPTION);
    
    if (confirm == JOptionPane.YES_OPTION) {
        ClienteDAO dao = new ClienteDAO();
        if (dao.excluir(Integer.parseInt(id))) {
            JOptionPane.showMessageDialog(this, "Cliente excluído com sucesso!");
            carregarClientes();
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao excluir cliente!");
        }
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
      int linhaSelecionada = jTable1.getSelectedRow();
    if (linhaSelecionada == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um cliente para editar!");
        return;
    }
    
    String id = jTable1.getValueAt(linhaSelecionada, 0).toString();
    String nome = jTable1.getValueAt(linhaSelecionada, 1).toString();
    String cpf = jTable1.getValueAt(linhaSelecionada, 2).toString();
    String endereco = jTable1.getValueAt(linhaSelecionada, 3).toString();
    
    JTextField txtNome = new JTextField(nome);
    JTextField txtCpf = new JTextField(cpf);
    JTextField txtEndereco = new JTextField(endereco);
    
    Object[] message = {
        "Nome:", txtNome,
        "CPF:", txtCpf,
        "Endereço:", txtEndereco
    };
    
    int option = JOptionPane.showConfirmDialog(this, message, "Editar Cliente", JOptionPane.OK_CANCEL_OPTION);
    if (option == JOptionPane.OK_OPTION) {
        Cliente cliente = new Cliente(id, txtNome.getText().trim(), txtCpf.getText().trim(), txtEndereco.getText().trim());
        ClienteDAO dao = new ClienteDAO();
        
        if (dao.atualizar(cliente)) {
            JOptionPane.showMessageDialog(this, "Cliente atualizado com sucesso!");
            carregarClientes();
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao atualizar cliente!");
        }
    }
    }//GEN-LAST:event_jButton3ActionPerformed

