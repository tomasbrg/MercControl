    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (carrinho.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Nenhum produto no carrinho!");
        return;
    }
    
    int confirm = JOptionPane.showConfirmDialog(this, 
        "Confirmar venda no valor de " + jLabel4.getText() + "?", 
        "Confirmar Venda", 
        JOptionPane.YES_NO_OPTION);
    
    if (confirm == JOptionPane.YES_OPTION) {
        VendaDAO vendaDAO = new VendaDAO();
        int vendaId = vendaDAO.registrarVenda(-1, totalCompra);
        
        if (vendaId > 0) {
            ProdutoDAO produtoDAO = new ProdutoDAO();
            
            for (ItemVenda item : carrinho) {
                vendaDAO.adicionarItemVenda(vendaId, 
                    Integer.parseInt(item.getProdutoId()), 
                    item.getQuantidade(), 
                    item.getPreco());
                
                Produto produto = produtoDAO.buscarPorId(Integer.parseInt(item.getProdutoId()));
                int novaQuantidade = produto.getQuantidade() - item.getQuantidade();
                produtoDAO.atualizarQuantidade(Integer.parseInt(item.getProdutoId()), novaQuantidade);
            }
            
            JOptionPane.showMessageDialog(this, "Venda realizada com sucesso!");
            carrinho.clear();
            atualizarTabela();
            quantidadeAtual = 1;
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao registrar venda!");
        }
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String idStr = jTextField1.getText().trim();
    if (idStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Digite o ID do produto!");
        return;
    }
    
    try {
        int id = Integer.parseInt(idStr);
        ProdutoDAO dao = new ProdutoDAO();
        Produto produto = dao.buscarPorId(id);
        
        if (produto == null) {
            JOptionPane.showMessageDialog(this, "Produto não encontrado!");
            return;
        }
        
        if (produto.getQuantidade() <= 0) {
            JOptionPane.showMessageDialog(this, "Produto sem estoque!");
            return;
        }
        
       
        for (ItemVenda item : carrinho) {
            if (item.getProdutoId().equals(String.valueOf(id))) {
                int novaQtd = item.getQuantidade() + quantidadeAtual;
                if (novaQtd > produto.getQuantidade()) {
                    JOptionPane.showMessageDialog(this, "Quantidade excede o estoque disponível!");
                    return;
                }
                item.setQuantidade(novaQtd);
                atualizarTabela();
                jTextField1.setText("");
                return;
            }
        }
        
       
        if (quantidadeAtual > produto.getQuantidade()) {
            JOptionPane.showMessageDialog(this, "Quantidade excede o estoque disponível!");
            return;
        }
        
        ItemVenda novoItem = new ItemVenda(
            String.valueOf(id),
            produto.getNome(),
            produto.getPreco(),
            quantidadeAtual
        );
        carrinho.add(novoItem);
        atualizarTabela();
        jTextField1.setText("");
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ID inválido!");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

