    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nome = jTextField3.getText().trim();
    String precoStr = jTextField2.getText().trim();
    String quantidadeStr = jTextField1.getText().trim();
    String tipo = (String) jComboBox1.getSelectedItem();
    
    if (nome.isEmpty() || precoStr.isEmpty() || quantidadeStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
        return;
    }
    
    try {
        double preco = Double.parseDouble(precoStr);
        int quantidade = Integer.parseInt(quantidadeStr);
        
        Produto produto = new Produto("0", nome, tipo, false, preco, quantidade);
        ProdutoDAO dao = new ProdutoDAO();
        
        if (dao.inserir(produto)) {
            JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso!");
            limparCampos();
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao cadastrar produto!");
        }
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Preço e quantidade devem ser números válidos!");
    }
    }//GEN-LAST:event_jButton1ActionPerformed
private void limparCampos() {
    jTextField3.setText("");
    jTextField2.setText("");
    jTextField1.setText("");
    jComboBox1.setSelectedIndex(0);
}
