    private void carregarRelatorio() {
    VendaDAO vendaDAO = new VendaDAO();
    

    double total = vendaDAO.getTotalVendas();
    jLabel3.setText(String.format("R$ %.2f", total));  // ou o label que mostra o total
    
    
    DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
    model.setRowCount(0);
    
    List<Map<String, Object>> vendas = vendaDAO.getRelatorioVendas();
    for (Map<String, Object> venda : vendas) {
        model.addRow(new Object[]{
            venda.get("id"),
            venda.get("cliente"),
            venda.get("data"),
            String.format("R$ %.2f", venda.get("total"))
        });
    }
}

